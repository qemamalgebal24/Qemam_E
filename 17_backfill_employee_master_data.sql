-- ============================================================================
-- إصلاح لمرة واحدة: تعبئة بيانات الموظف المركزي (الراتب / نوع الأجر / سعر
-- الساعة الإضافي) من آخر شهر رواتب موجود له فيه بيانات — لتصحيح الأرقام
-- اللي فاضلة صفر في "الإعدادات ← الموظفين" رغم إن الراتب الحقيقي موجود
-- جوه كشوف الشهور. شغّلي هذا الملف مرة واحدة بعد ما ترفعي index.html المحدّث
-- (اللي فيه إصلاح المزامنة التلقائية من الشهر للموظف من دلوقتي فصاعدًا).
-- آمن تمامًا: بيقرأ بس من آخر شهر لكل موظف ويحدّث سجله المركزي، ومش بيمسح
-- أو يغيّر أي بيانات داخل كشوف الشهور نفسها.
-- ============================================================================

update public.employees e
set
  salary   = pe.salary,
  wage_type = coalesce(pe.wage_type, e.wage_type),
  ot_rate  = coalesce(pe.ot_rate, e.ot_rate)
from (
  -- لكل موظف: آخر صف له في أحدث شهر (بالترتيب) عنده فيه بيانات فعلاً
  select distinct on (pe.employee_id)
    pe.employee_id, pe.salary, pe.wage_type, pe.ot_rate
  from public.payroll_entries pe
  join public.payroll_sheets ps on ps.id = pe.sheet_id
  where pe.employee_id is not null
  order by pe.employee_id, ps.sort_order desc, pe.id desc
) pe
where pe.employee_id = e.id;

