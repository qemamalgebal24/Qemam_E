-- (مأخوذ من آخر شهر داخل فيه). أي موظف "معندوش شهر أصلاً" (زي الموظفين
-- الجدد اللي اتضافوا في الإعدادات ولسه ماتحطوش في أي كشف شهر) هيفضل
-- زي ما هو، لأنه معندوش بيانات نرجع نجيبها منها.
